"""
train_model.py

Preserves the ORIGINAL model logic from the user's notebook
(Ml model house pricing.ipynb):
    - Algorithm: sklearn.linear_model.LinearRegression
    - Features (in this exact order): Area (sqft), Bedrooms, Age
    - Target: Price (in lakhs)
    - No scaling, no categorical encoding (none of the original
      features are categorical, so none was used in the source notebook)

The ONLY change from the original notebook is the training data.
The original notebook used 5 hand-typed rows, which is not enough
data to fit or evaluate a model meaningfully. At the user's request,
this script replaces those 5 rows with a larger, realistic SYNTHETIC
dataset (same 3 features, same target, same relationship direction:
price rises with area and bedrooms, falls with age) so the deployed
model has something real to learn from.

This dataset is synthetic (generated with a fixed random seed for
reproducibility) -- it is NOT scraped or sourced from real listings.
That is disclosed in the README and in the app's About/Insights copy.
Any metrics this script prints/saves are computed directly from this
run, never hand-typed or invented.
"""

import json
from pathlib import Path

import joblib
import numpy as np
import pandas as pd
from sklearn.linear_model import LinearRegression
from sklearn.metrics import mean_absolute_error, mean_squared_error, r2_score
from sklearn.model_selection import train_test_split

RANDOM_SEED = 42
N_SAMPLES = 600

FEATURE_ORDER = ["Area (sqft)", "Bedrooms", "Age"]
TARGET_COL = "Price (in lakhs)"

HERE = Path(__file__).resolve().parent
DATA_DIR = HERE.parent / "data"
DATA_DIR.mkdir(parents=True, exist_ok=True)

CSV_PATH = DATA_DIR / "house_prices.csv"
MODEL_PATH = HERE / "house_price_model.joblib"
METRICS_PATH = HERE / "metrics.json"


def generate_dataset(n=N_SAMPLES, seed=RANDOM_SEED) -> pd.DataFrame:
    rng = np.random.default_rng(seed)

    area = rng.uniform(500, 4000, n)
    # Bedrooms loosely scale with area, like real listings, plus noise
    bedrooms = np.clip(np.round(area / 650 + rng.normal(0, 0.6, n)), 1, 6)
    age = rng.uniform(0, 30, n)

    # Same relationship direction as the original toy example:
    # price rises with area and bedrooms, falls with age.
    base_price = (
        0.035 * area
        + 6.0 * bedrooms
        - 0.45 * age
        + 5.0
    )
    noise = rng.normal(0, 8, n)
    price = np.clip(base_price + noise, 8, None)

    df = pd.DataFrame(
        {
            FEATURE_ORDER[0]: area.round(0),
            FEATURE_ORDER[1]: bedrooms.astype(int),
            FEATURE_ORDER[2]: age.round(1),
            TARGET_COL: price.round(2),
        }
    )
    return df


def train_and_save():
    df = generate_dataset()
    df.to_csv(CSV_PATH, index=False)

    X = df[FEATURE_ORDER]
    y = df[TARGET_COL]

    X_train, X_test, y_train, y_test = train_test_split(
        X, y, test_size=0.2, random_state=RANDOM_SEED
    )

    model = LinearRegression()
    model.fit(X_train, y_train)

    y_pred = model.predict(X_test)

    metrics = {
        "r2_score": round(float(r2_score(y_test, y_pred)), 4),
        "mae_lakhs": round(float(mean_absolute_error(y_test, y_pred)), 2),
        "rmse_lakhs": round(float(np.sqrt(mean_squared_error(y_test, y_pred))), 2),
        "n_train": int(len(X_train)),
        "n_test": int(len(X_test)),
        "feature_order": FEATURE_ORDER,
        "coefficients": {
            FEATURE_ORDER[i]: round(float(c), 6)
            for i, c in enumerate(model.coef_)
        },
        "intercept": round(float(model.intercept_), 4),
        "dataset": "synthetic (generated by train_model.py, seed=42, n=600)",
    }

    joblib.dump({"model": model, "feature_order": FEATURE_ORDER}, MODEL_PATH)
    METRICS_PATH.write_text(json.dumps(metrics, indent=2))

    print("Model trained and saved to:", MODEL_PATH)
    print(json.dumps(metrics, indent=2))


if __name__ == "__main__":
    train_and_save()
